const localesDir = path.join(process.cwd(), 'src/i18n/locales');
const languages = Object.keys(translations);

for (const lang of languages) {
  const filePath = path.join(localesDir, `${lang}.ts`);
  if (!fs.existsSync(filePath)) {
    console.error(`File not found: ${filePath}`);
    continue;
  }
  let content = fs.readFileSync(filePath, 'utf-8');
  const data = translations[lang];

  // 1. Inject or merge into `common: {`
  if (data.common) {
    const commonEntries = Object.entries(data.common)
      .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
      .join('\n');
    content = content.replace(/(\bcommon\s*:\s*\{)/, `$1\n${commonEntries}`);
  }

  // 2. Inject or merge into `prashna: {`
  if (data.prashna) {
    const prashnaEntries = Object.entries(data.prashna)
      .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
      .join('\n');
    content = content.replace(/(\bprashna\s*:\s*\{)/, `$1\n${prashnaEntries}`);
  }

  // 3. Inject or merge into `pratah: {`
  if (data.pratah) {
    const pratahEntries = Object.entries(data.pratah)
      .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
      .join('\n');
    content = content.replace(/(\bpratah\s*:\s*\{)/, `$1\n${pratahEntries}`);
  }

  // 4. Inject or merge into `kundli: {`
  if (data.kundli) {
    const kundliEntries = Object.entries(data.kundli)
      .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
      .join('\n');
    content = content.replace(/(\bkundli\s*:\s*\{)/, `$1\n${kundliEntries}`);
  }

  // 5. Inject `dailyCompanion: { ... },` before `report: {`
  if (data.dailyCompanion) {
    const companionObj = `  dailyCompanion: ${JSON.stringify(data.dailyCompanion, null, 4).replace(/\n/g, '\n  ')},\n`;
    content = content.replace(/(\n\s*report\s*:\s*\{)/, `\n${companionObj}$1`);
  }

  fs.writeFileSync(filePath, content, 'utf-8');
  console.log(`Updated locale file: ${lang}.ts`);
}
