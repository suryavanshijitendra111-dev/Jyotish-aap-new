export function getLocalizedPlane(planeName: string, lang: LanguageCode): LocalizedLoShuPlane {
  const item = PLANE_TRANSLATIONS[planeName];
  if (!item) return { name: planeName, description: '' };
  const localized = item[lang] || item['hi'] || item['en'];
  if (!localized) return { name: planeName, description: '' };
  return { name: localized.name, description: localized.desc };
}

export function getLocalizedArrow(arrowName: string, lang: LanguageCode): LocalizedLoShuArrow {
  const item = ARROW_TRANSLATIONS[arrowName];
  if (!item) return { name: arrowName, description: '' };
  const localized = item[lang] || item['hi'] || item['en'];
  if (!localized) return { name: arrowName, description: '' };
  return { name: localized.name, description: localized.desc };
}

export function getLocalizedDominantPlanes(planesStr: string, lang: LanguageCode): string {
  if (!planesStr || lang === 'en') return planesStr;
  let res = planesStr;
  res = res.replace(/Mental Plane/g, getLocalizedPlane('Mental Plane', lang).name);
  res = res.replace(/Emotional Plane/g, getLocalizedPlane('Emotional Plane', lang).name);
  res = res.replace(/Practical Plane/g, getLocalizedPlane('Practical Plane', lang).name);
  return res;
}
